-- =====================================================================
-- Project Pulse :: core relational schema (PostgreSQL 15+)
-- Covers: identity/RBAC, academic structure, teams, projects, milestones,
-- tasks, deliverables + versions, reviews/feedback, contribution evidence,
-- risk assessments, similarity reviews and the audit trail.
-- =====================================================================
CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- crypt(), gen_salt(), digest()
CREATE EXTENSION IF NOT EXISTS pg_trgm;    -- fuzzy title search
CREATE EXTENSION IF NOT EXISTS vector;     -- pgvector (see pgvector.sql)

-- ---------------------------------------------------------------------
-- 1. Identity & RBAC
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  role_id    SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name  TEXT NOT NULL UNIQUE
             CHECK (role_name IN ('student','faculty','coordinator','admin'))
);

CREATE TABLE departments (
  department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL UNIQUE,
  code          TEXT NOT NULL UNIQUE CHECK (code = upper(code))
);

CREATE TABLE users (
  user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          TEXT NOT NULL UNIQUE CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  password_hash  TEXT NOT NULL,                       -- bcrypt via pgcrypto crypt()
  full_name      TEXT NOT NULL,
  department_id  BIGINT REFERENCES departments(department_id) ON DELETE SET NULL,
  enrollment_no  TEXT UNIQUE,                         -- students only
  is_active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_users_department ON users(department_id);

CREATE TABLE user_roles (                             -- M:N users <-> roles
  user_id BIGINT   NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  role_id SMALLINT NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
  PRIMARY KEY (user_id, role_id)
);
CREATE INDEX idx_user_roles_role ON user_roles(role_id);

-- ---------------------------------------------------------------------
-- 2. Academic structure & teams
-- ---------------------------------------------------------------------
CREATE TABLE courses (
  course_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id BIGINT NOT NULL REFERENCES departments(department_id) ON DELETE RESTRICT,
  code          TEXT NOT NULL UNIQUE,
  title         TEXT NOT NULL,
  semester      TEXT NOT NULL,
  academic_year TEXT NOT NULL CHECK (academic_year ~ '^\d{4}-\d{2}$')
);
CREATE INDEX idx_courses_department ON courses(department_id);

CREATE TABLE teams (
  team_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (course_id, name)
);

CREATE TABLE team_members (
  team_id     BIGINT NOT NULL REFERENCES teams(team_id) ON DELETE CASCADE,
  user_id     BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  member_role TEXT   NOT NULL DEFAULT 'member' CHECK (member_role IN ('leader','member')),
  joined_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (team_id, user_id)
);
CREATE INDEX idx_team_members_user ON team_members(user_id);

-- ---------------------------------------------------------------------
-- 3. Projects & guide allocation
-- ---------------------------------------------------------------------
CREATE TABLE projects (
  project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id    BIGINT NOT NULL UNIQUE REFERENCES teams(team_id) ON DELETE CASCADE, -- one project per team
  course_id  BIGINT NOT NULL REFERENCES courses(course_id) ON DELETE RESTRICT,
  title      TEXT NOT NULL CHECK (char_length(title) BETWEEN 5 AND 200),
  abstract   TEXT NOT NULL CHECK (char_length(abstract) >= 30),
  status     TEXT NOT NULL DEFAULT 'proposed'
             CHECK (status IN ('proposed','approved','in_progress','completed','rejected')),
  start_date DATE,
  end_date   DATE,
  created_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE INDEX idx_projects_course  ON projects(course_id);
CREATE INDEX idx_projects_status  ON projects(status);
CREATE INDEX idx_projects_title_trgm ON projects USING gin (title gin_trgm_ops);

CREATE TABLE guide_allocations (
  allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id    BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  guide_id      BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  allocated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  is_active     BOOLEAN NOT NULL DEFAULT TRUE
);
-- A project has at most ONE active guide (partial unique index).
CREATE UNIQUE INDEX uq_guide_allocations_active ON guide_allocations(project_id) WHERE is_active;
CREATE INDEX idx_guide_allocations_guide ON guide_allocations(guide_id) WHERE is_active;

-- ---------------------------------------------------------------------
-- 4. Milestones, tasks, assignments
-- ---------------------------------------------------------------------
CREATE TABLE milestones (
  milestone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id   BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  description  TEXT,
  sequence_no  INT  NOT NULL CHECK (sequence_no > 0),
  due_date     DATE NOT NULL,
  status       TEXT NOT NULL DEFAULT 'pending'
               CHECK (status IN ('pending','submitted','under_review','approved','changes_requested')),
  weight       NUMERIC(5,2) NOT NULL DEFAULT 10 CHECK (weight > 0 AND weight <= 100),
  submitted_at TIMESTAMPTZ,
  approved_at  TIMESTAMPTZ,
  UNIQUE (project_id, sequence_no),
  CHECK (status <> 'approved' OR approved_at IS NOT NULL)
);
CREATE INDEX idx_milestones_project_due ON milestones(project_id, due_date);
CREATE INDEX idx_milestones_open_due ON milestones(due_date) WHERE status IN ('pending','changes_requested');

CREATE TABLE tasks (
  task_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  milestone_id    BIGINT NOT NULL REFERENCES milestones(milestone_id) ON DELETE CASCADE,
  title           TEXT NOT NULL,
  description     TEXT,
  status          TEXT NOT NULL DEFAULT 'todo' CHECK (status IN ('todo','in_progress','done','blocked')),
  priority        TEXT NOT NULL DEFAULT 'medium' CHECK (priority IN ('low','medium','high')),
  due_date        DATE,
  estimated_hours NUMERIC(6,2) CHECK (estimated_hours IS NULL OR estimated_hours > 0),
  completed_at    TIMESTAMPTZ,
  CHECK (status <> 'done' OR completed_at IS NOT NULL)
);
CREATE INDEX idx_tasks_milestone ON tasks(milestone_id);
CREATE INDEX idx_tasks_status_due ON tasks(status, due_date);

CREATE TABLE task_assignments (                       -- M:N tasks <-> users
  task_id      BIGINT NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
  user_id      BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  assigned_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  hours_logged NUMERIC(6,2) NOT NULL DEFAULT 0 CHECK (hours_logged >= 0),
  PRIMARY KEY (task_id, user_id)
);
CREATE INDEX idx_task_assignments_user ON task_assignments(user_id);

-- ---------------------------------------------------------------------
-- 5. Deliverables & versions (binary/text artefacts; rich SRS content lives in MongoDB)
-- ---------------------------------------------------------------------
CREATE TABLE deliverables (
  deliverable_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  milestone_id       BIGINT NOT NULL UNIQUE REFERENCES milestones(milestone_id) ON DELETE CASCADE,
  submitted_by       BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  title              TEXT NOT NULL,
  current_version_no INT NOT NULL DEFAULT 0 CHECK (current_version_no >= 0),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE document_versions (
  version_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deliverable_id   BIGINT NOT NULL REFERENCES deliverables(deliverable_id) ON DELETE CASCADE,
  version_no       INT NOT NULL CHECK (version_no > 0),
  file_name        TEXT NOT NULL,
  file_url         TEXT,
  checksum         TEXT NOT NULL,                      -- sha256 hex of the submitted payload
  mongo_version_id TEXT,                               -- cross-DB pointer -> srs_documents.versions._id
  change_summary   TEXT NOT NULL,
  uploaded_by      BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  uploaded_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (deliverable_id, version_no)
);
CREATE INDEX idx_document_versions_uploaded ON document_versions(deliverable_id, uploaded_at DESC);

-- ---------------------------------------------------------------------
-- 6. Reviews & feedback workflow
-- ---------------------------------------------------------------------
CREATE TABLE reviews (
  review_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  milestone_id BIGINT NOT NULL REFERENCES milestones(milestone_id) ON DELETE CASCADE,
  reviewer_id  BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  decision     TEXT NOT NULL CHECK (decision IN ('approved','changes_requested')),
  score        NUMERIC(5,2) CHECK (score IS NULL OR score BETWEEN 0 AND 100),
  comments     TEXT,
  reviewed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reviews_milestone ON reviews(milestone_id, reviewed_at DESC);

CREATE TABLE feedback_items (
  feedback_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id       BIGINT REFERENCES reviews(review_id) ON DELETE SET NULL,
  milestone_id    BIGINT REFERENCES milestones(milestone_id) ON DELETE CASCADE,
  project_id      BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  author_id       BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  body            TEXT NOT NULL CHECK (char_length(body) >= 3),
  severity        TEXT NOT NULL DEFAULT 'medium' CHECK (severity IN ('low','medium','high','critical')),
  status          TEXT NOT NULL DEFAULT 'open'
                  CHECK (status IN ('open','in_progress','resolved','verified','wont_fix')),
  resolution_note TEXT,
  resolved_by     BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  resolved_at     TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- A resolved/verified item must carry evidence of how it was resolved.
  CHECK (status NOT IN ('resolved','verified') OR (resolved_at IS NOT NULL AND resolution_note IS NOT NULL))
);
CREATE INDEX idx_feedback_project_status ON feedback_items(project_id, status);
CREATE INDEX idx_feedback_open_severity ON feedback_items(severity) WHERE status IN ('open','in_progress');

-- ---------------------------------------------------------------------
-- 7. Contribution evidence, risk, similarity, audit
-- ---------------------------------------------------------------------
CREATE TABLE contribution_evidence (
  evidence_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id    BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  user_id       BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  task_id       BIGINT REFERENCES tasks(task_id) ON DELETE SET NULL,
  evidence_type TEXT NOT NULL CHECK (evidence_type IN ('commit','document','meeting','review','other')),
  description   TEXT NOT NULL,
  evidence_url  TEXT,
  weight        NUMERIC(6,2) NOT NULL DEFAULT 1 CHECK (weight >= 0),
  recorded_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_evidence_project_user ON contribution_evidence(project_id, user_id);

CREATE TABLE risk_assessments (                       -- append-only history of computed risk
  risk_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  risk_score  NUMERIC(5,2) NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
  risk_level  TEXT NOT NULL CHECK (risk_level IN ('low','medium','high','critical')),
  factors     JSONB NOT NULL DEFAULT '{}'::jsonb,
  assessed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_risk_project_time ON risk_assessments(project_id, assessed_at DESC);
CREATE INDEX idx_risk_level ON risk_assessments(risk_level);

CREATE TABLE similarity_reviews (
  similarity_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id         BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  matched_project_id BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  similarity_score   NUMERIC(5,4) NOT NULL CHECK (similarity_score BETWEEN -1 AND 1),
  reviewer_id        BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  decision           TEXT NOT NULL DEFAULT 'pending'
                     CHECK (decision IN ('pending','acceptable','plagiarism_suspected','duplicate')),
  notes              TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at        TIMESTAMPTZ,
  CHECK (project_id <> matched_project_id),
  UNIQUE (project_id, matched_project_id)
);
CREATE INDEX idx_similarity_pending ON similarity_reviews(project_id) WHERE decision = 'pending';

CREATE TABLE audit_logs (                             -- no FK on changed_by: logs must outlive users
  audit_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name TEXT NOT NULL,
  record_id  TEXT NOT NULL,
  action     TEXT NOT NULL,
  old_data   JSONB,
  new_data   JSONB,
  changed_by BIGINT,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_record ON audit_logs(table_name, record_id);
CREATE INDEX idx_audit_time   ON audit_logs(changed_at DESC);
